export function isTestPath(rel: string): boolean {
  const p = rel.toLowerCase();
  return /(^|\/)(__tests__|tests?|spec|e2e|cypress|playwright)\//.test(p) || /\.(test|spec)\.[a-z]+$/.test(p) || /(^|\/)test_[^/]+\.py$/.test(p) || /_test\.(py|go)$/.test(p) || /conftest\.py$/.test(p);
}

export function isGenerated(rel: string, content: string): boolean {
  if (/\.min\.(js|css)$/.test(rel)) return true;
  const head = content.slice(0, 400);
  if (/@generated|DO NOT EDIT|auto-generated|autogenerated/i.test(head)) return true;
  // very long single-line files are bundles
  const firstNl = content.indexOf("\n");
  return content.length > 20_000 && (firstNl === -1 || firstNl > 5000);
}
