/** Languages with full AST support in DevForge's engine. */
export const AST_LANGS = new Set(["typescript", "javascript", "python"]);

export function detectLanguage(rel: string): string | null {
  const base = path.basename(rel);
  if (NAMES[base]) return NAMES[base];
  if (base.startsWith(".env")) return "dotenv";
  return EXT[path.extname(base).toLowerCase()] ?? null;
}

